let currentLang = localStorage.getItem('presentit_lang') || 'en';

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('presentit_lang', lang);
  updatePageTranslations();
  
  // Dispatch custom event
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function getTranslation(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

function updatePageTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = getTranslation(key);
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.placeholder = getTranslation(key);
    }
  });

  // Update active option in lang selectors
  document.querySelectorAll('.lang-select-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
  });
}

function renderLangSelector(container) {
  if (typeof container === 'string') {
    container = document.getElementById(container);
  }
  if (!container) return;

  const languages = [
    { code: 'en', label: '🇬🇧 EN' },
    { code: 'de', label: '🇩🇪 DE' },
    { code: 'fr', label: '🇫🇷 FR' },
    { code: 'zh', label: '🇨🇳 中文' }
  ];

  container.innerHTML = `
    <div class="lang-selector-bar" style="display:inline-flex;gap:4px;background:rgba(255,255,255,0.06);border:1px solid rgba(255,255,255,0.12);padding:3px;border-radius:10px;">
      ${languages.map(l => `
        <button class="lang-select-btn ${l.code === currentLang ? 'active' : ''}" data-lang="${l.code}" onclick="setLanguage('${l.code}')" style="background:${l.code === currentLang ? 'rgba(255,255,255,0.2)' : 'transparent'};color:${l.code === currentLang ? '#fff' : 'var(--muted, #94a3b8)'};border:none;border-radius:7px;padding:4px 10px;font-size:12px;font-weight:700;cursor:pointer;transition:all 0.2s;">
          ${l.label}
        </button>
      `).join('')}
    </div>
  `;
}

// Auto update on load
document.addEventListener('DOMContentLoaded', () => {
  updatePageTranslations();
});
